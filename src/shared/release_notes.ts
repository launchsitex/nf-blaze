/** השורות שצריך להציג למי שקופץ מגרסה לגרסה */
export function notesSince(
  previousVersion: string | undefined,
  currentVersion: string,
  compare: (a: string, b: string) => number
): ReleaseNote[] {
  return RELEASE_NOTES.filter((n) => {
    if (compare(n.version, currentVersion) > 0) return false // עוד לא הותקנה
    if (!previousVersion) return compare(n.version, currentVersion) === 0
    return compare(n.version, previousVersion) > 0
  })
}
